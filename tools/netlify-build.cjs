#!/usr/bin/env node
// Netlify build step: writes drive-config.js from the DRIVE_API_KEY and DRIVE_FOLDER_ID environment
// variables, so the key is not in the repo.
'use strict';
const fs = require('fs');
const path = require('path');

const apiKey = process.env.DRIVE_API_KEY || '';
const folderId = process.env.DRIVE_FOLDER_ID || '';
const out = path.join(__dirname, '..', 'drive-config.js');

if (!apiKey || !folderId) {
  console.log('DRIVE_API_KEY / DRIVE_FOLDER_ID not set: no Google Drive songs.');
} else {
  fs.writeFileSync(out, '// Generated by tools/netlify-build.cjs\nwindow.KARAOKE_DRIVE = ' + JSON.stringify({ apiKey: apiKey, folderId: folderId }) + ';\n');
  console.log('drive-config.js written (folder ' + folderId + ').');
}

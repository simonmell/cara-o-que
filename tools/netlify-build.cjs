#!/usr/bin/env node
// Build step for Netlify (see netlify.toml): writes drive-config.js with the Google Drive key and folder taken from
// the site's environment variables DRIVE_API_KEY and DRIVE_FOLDER_ID, so the key never has to be in the repository.
// Without those variables it writes nothing and the site uses only the songs that come with it.
'use strict';
const fs = require('fs');
const path = require('path');

const apiKey = process.env.DRIVE_API_KEY || '';
const folderId = process.env.DRIVE_FOLDER_ID || '';
const out = path.join(__dirname, '..', 'drive-config.js');

if (!apiKey || !folderId) {
  console.log('DRIVE_API_KEY / DRIVE_FOLDER_ID not set: no Google Drive songs.');
} else {
  fs.writeFileSync(out, '// Generated by tools/netlify-build.cjs\nwindow.KARAOKE_DRIVE = ' + JSON.stringify({ apiKey: apiKey, folderId: folderId }) + ';\n');
  console.log('drive-config.js written (folder ' + folderId + ').');
}

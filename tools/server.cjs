#!/usr/bin/env node
// Local karaoke server: serves the project folder at http://127.0.0.1:8080/ so it can be used on this
// computer. It is needed because browsers do not load JavaScript modules or the audio processor
// (AudioWorklet) from file://, that is, when index.html is double-clicked.
//
// Usage:  node tools/server.cjs [--open] [--port 8080]
//   --open    opens the karaoke in the default browser once the server is ready
//   --port    port to use (if it is taken or reserved, others are tried; see CANDIDATES)
//
// Started by «Open karaoke.bat». Nothing needs to be installed: it only uses modules that ship with Node.
// It listens on 127.0.0.1 only, so it cannot be reached from other computers on the network.
// Other computers use the published web version (see «Build web version.bat»).
//
// Besides the files, it generates songs/list.js on the fly (the song list with their .txt files), so a new
// song copied into «songs» shows up just by reloading the page.
//
// Written in CommonJS without modern syntax (no import, no async/await) so it also works with old versions
// of Node (from 6 on). The .cjs extension keeps recent versions from treating it as an ES module.
'use strict';

const http = require('http');
const fs = require('fs');
const path = require('path');
const spawn = require('child_process').spawn;

const ROOT = path.resolve(__dirname, '..');
const SONGS = path.join(ROOT, 'songs');
const HOST = '127.0.0.1';
const MARKER = '/__cara-o-que';   // path that answers «I am the karaoke server» (so it is not started twice)

// ── Command-line options ──────────────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const openBrowserFlag = args.indexOf('--open') >= 0;
const iPort = args.indexOf('--port');
const PORT = iPort >= 0 ? Number(args[iPort + 1]) : Number(process.env.PORT || 8080);

// ── File types ────────────────────────────────────────────────────────────────────────────────────
const MIME = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.txt': 'text/plain; charset=utf-8',
  '.md': 'text/plain; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.gif': 'image/gif', '.ico': 'image/x-icon',
  '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.oga': 'audio/ogg', '.opus': 'audio/ogg', '.m4a': 'audio/mp4',
  '.aac': 'audio/aac', '.wav': 'audio/wav', '.flac': 'audio/flac', '.weba': 'audio/webm',
  '.mp4': 'video/mp4', '.m4v': 'video/mp4', '.webm': 'video/webm', '.woff2': 'font/woff2',
};
const mimeType = (f) => MIME[path.extname(f).toLowerCase()] || 'application/octet-stream';
const byName = (a, b) => a.localeCompare(b);

// Entries of a folder split into files and subfolders (hidden ones left out)
function entries(dir) {
  const r = { files: [], folders: [] };
  fs.readdirSync(dir).forEach((n) => {
    if (n.charAt(0) === '.') return;
    let st;
    try { st = fs.statSync(path.join(dir, n)); } catch (e) { return; }
    if (st.isDirectory()) r.folders.push(n); else if (st.isFile()) r.files.push(n);
  });
  r.files.sort(byName); r.folders.sort(byName);
  return r;
}

// ── songs/list.js generated on the fly ────────────────────────────────────────────────────────────
// One entry per folder that has UltraStar .txt files, with the list of files and each .txt in base64 (so their
// encoding does not matter). Read by js/songs/song-library.js.
function songList() {
  if (!fs.existsSync(SONGS)) fs.mkdirSync(SONGS);
  const folders = [];
  [''].concat(entries(SONGS).folders).forEach((rel) => {
    const dir = path.join(SONGS, rel);
    const files = entries(dir).files.filter((n) => n !== 'list.js');
    const txt = {};
    files.forEach((n) => {
      if (!/\.txt$/i.test(n)) return;
      const f = path.join(dir, n);
      if (fs.statSync(f).size < 1048576) txt[n] = fs.readFileSync(f).toString('base64');
    });
    if (Object.keys(txt).length) folders.push({ folder: rel, files: files, txt: txt });
  });
  return '// Generated by tools/server.cjs on ' + new Date().toISOString() + '.\n' +
    'window.KARAOKE_SONGS = ' + JSON.stringify({ folders: folders }).replace(/<\//g, '<\\/') + ';\n';
}

// ── Folder listing (fallback: the page reads it if there is no list.js) ───────────────────────────
function listing(dir, url) {
  const e = entries(dir);
  const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
  const items = e.folders.map((n) => '<li><a href="' + esc(encodeURIComponent(n)) + '/">' + esc(n) + '/</a></li>')
    .concat(e.files.map((n) => '<li><a href="' + esc(encodeURIComponent(n)) + '">' + esc(n) + '</a></li>'));
  return '<!doctype html><meta charset="utf-8"><title>' + esc(url) + '</title><ul>\n' + items.join('\n') + '\n</ul>\n';
}

// ── Handling each request ─────────────────────────────────────────────────────────────────────────
function handle(req, res) {
  // No caching: a code change shows up just by reloading the page
  res.setHeader('Cache-Control', 'no-store');
  if (req.method !== 'GET' && req.method !== 'HEAD') { res.writeHead(405); res.end(); return; }

  let url;
  try { url = decodeURIComponent(req.url.split('?')[0].split('#')[0]); } catch (e) { res.writeHead(400); res.end(); return; }
  if (url === MARKER) { res.writeHead(200, { 'Content-Type': 'text/plain' }); res.end('cara-o-que'); return; }
  if (url === '/songs/list.js') { sendText(req, res, songList(), MIME['.js']); return; }

  // Path of the requested file, without leaving the project folder or entering hidden folders (.git)
  const file = path.join(ROOT, path.normalize(url));
  if (file !== ROOT && file.indexOf(ROOT + path.sep) !== 0) { res.writeHead(403); res.end(); return; }
  if (path.relative(ROOT, file).split(path.sep).some((p) => p.charAt(0) === '.')) { res.writeHead(404); res.end(); return; }

  let st;
  try { st = fs.statSync(file); } catch (e) {
    res.writeHead(404, { 'Content-Type': MIME['.txt'] }); res.end('Not found'); return;
  }
  if (st.isDirectory()) {
    if (url.charAt(url.length - 1) !== '/') { res.writeHead(301, { Location: encodeURI(url) + '/' }); res.end(); return; }
    const index = path.join(file, 'index.html');
    if (fs.existsSync(index)) { sendFile(req, res, index, fs.statSync(index)); return; }
    sendText(req, res, listing(file, url), MIME['.html']);
    return;
  }
  sendFile(req, res, file, st);
}

function sendText(req, res, text, mime) {
  const body = Buffer.from(text, 'utf8');
  res.writeHead(200, { 'Content-Type': mime, 'Content-Length': body.length });
  res.end(req.method === 'HEAD' ? undefined : body);
}

// Sends a file; with «Range» it sends only the requested piece (the player uses it to seek in the song)
function sendFile(req, res, file, st) {
  const head = { 'Content-Type': mimeType(file), 'Accept-Ranges': 'bytes' };
  const m = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range || '');
  let from = 0, to = st.size - 1, status = 200;
  if (m && (m[1] || m[2])) {
    if (m[1]) { from = Number(m[1]); if (m[2]) to = Math.min(Number(m[2]), st.size - 1); }
    else from = Math.max(0, st.size - Number(m[2]));   // «bytes=-500»: the last 500
    if (from > to || from >= st.size) {
      res.writeHead(416, { 'Content-Range': 'bytes */' + st.size }); res.end(); return;
    }
    status = 206; head['Content-Range'] = 'bytes ' + from + '-' + to + '/' + st.size;
  }
  head['Content-Length'] = to - from + 1;
  res.writeHead(status, head);
  if (req.method === 'HEAD' || st.size === 0) { res.end(); return; }
  fs.createReadStream(file, { start: from, end: to }).on('error', () => res.destroy()).pipe(res);
}

// ── Startup ───────────────────────────────────────────────────────────────────────────────────────

// Is a karaoke already running on that port (for example, if the .bat was opened twice)?
function alreadyRunning(port, done) {
  let finished = false;
  const finish = (v) => { if (!finished) { finished = true; done(v); } };
  const r = http.get({ host: HOST, port: port, path: MARKER }, (res) => {
    let t = ''; res.on('data', (c) => { t += c; }); res.on('end', () => finish(t === 'cara-o-que'));
  });
  r.on('error', () => finish(false));
  r.setTimeout(1500, () => { r.abort(); finish(false); });
}

function openBrowser(url) {
  const win = process.platform === 'win32';
  const cmd = win ? 'cmd' : process.platform === 'darwin' ? 'open' : 'xdg-open';
  const argv = win ? ['/c', 'start', '""', url] : [url];
  try {
    const p = spawn(cmd, argv, { stdio: 'ignore', detached: true, windowsVerbatimArguments: win });
    p.on('error', () => {}); p.unref();
  } catch (e) { /* no browser: the address stays printed in the console */ }
}

// Ports to try, in order. Besides being used by another program (EADDRINUSE), on Windows a port can be
// reserved by the system (Hyper-V, WSL and Docker reserve whole ranges, sometimes including 8080) and then
// listening fails with EACCES. So after the neighbors of the chosen port, ports from other ranges are tried and,
// finally, any free port the system hands out (0). The order is always the same, so on a given computer the
// karaoke always lands on the same port: this matters because the browser stores the preferences per address.
const CANDIDATES = [PORT, PORT + 1, PORT + 2, 8765, 18765, 28765, 38765, 5577, 0];

function ready(port) {
  const url = 'http://' + HOST + ':' + port + '/';
  console.log('Karaoke running at ' + url);
  if (port !== PORT) {
    console.log('(port ' + PORT + ' could not be used: it is taken or reserved by Windows)');
    if (CANDIDATES.indexOf(port) < 0) console.log('(this port changes every time, so saved preferences are not kept)');
  }
  console.log('To stop it, close this window or press Ctrl+C.');
  if (openBrowserFlag) openBrowser(url);
}

// Tries candidate i: if a karaoke is already there, opens it; if the port is free, listens; otherwise, the next one.
function tryPort(server, i) {
  const p = CANDIDATES[i];
  const attempt = () => {
    const failed = (e) => {
      server.removeListener('listening', listening);
      if ((e.code === 'EADDRINUSE' || e.code === 'EACCES') && i + 1 < CANDIDATES.length) tryPort(server, i + 1);
      else { console.error('Could not start the server: ' + e.message); process.exit(1); }
    };
    const listening = () => { server.removeListener('error', failed); ready(server.address().port); };
    server.once('error', failed);
    server.once('listening', listening);
    server.listen(p, HOST);
  };
  if (p === 0) { attempt(); return; }
  alreadyRunning(p, (running) => {
    if (!running) { attempt(); return; }
    const url = 'http://' + HOST + ':' + p + '/';
    console.log('The karaoke is already open at ' + url);
    if (openBrowserFlag) openBrowser(url);
  });
}

if (!fs.existsSync(path.join(ROOT, 'index.html'))) { console.error('index.html not found in ' + ROOT); process.exit(1); }
const server = http.createServer((req, res) => {
  try { handle(req, res); } catch (e) {
    console.error(e);
    if (!res.headersSent) res.writeHead(500);
    res.end();
  }
});
tryPort(server, 0);
